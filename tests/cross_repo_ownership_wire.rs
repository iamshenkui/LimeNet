/// Smoke test verifying all ownership_wire fixtures exist on disk.
#[test]
fn test_all_ownership_wire_fixtures_exist() {
    let expected = [
        "all_baseline_records.json",
        "frozen_graph_ownership_record.json",
        "local-derived.json",
        "local-derived-promoted.json",
        "local-original.json",
        "mirror-derived.json",
        "mirror-original.json",
        "promotion-derived-transfer.json",
        "promotion_intent.json",
        "promotion-transfer.json",
    ];
    for name in &expected {
        let path = wire_dir().join(name);
        assert!(
            path.exists(),
            "ownership_wire fixture must exist: {name}"
        );
    }
}
