// GAP-OWN-03: Empty-string promoted_from in mirror fixtures
// ---------------------------------------------------------------------------

/// Python emits `"promoted_from": ""` for mirror records.  The custom
/// `deserialize_empty_as_none` normalizer maps this to `None` so that the
/// mirror `invalid_transition` guardrail does not produce a false positive.
///
/// GAP-OWN-03 is resolved for `promoted_from` and `created_from` at the
/// serde deserialization layer.
#[test]
fn test_mirror_fixture_empty_promoted_from_normalized_to_none() {
    let json = read_wire_fixture("mirror-original.json");
    let ownership: Ownership = serde_json::from_str(&json).unwrap();
    // Python emitted "" — normalizer maps it to None
    assert!(
        ownership.promoted_from.is_none(),
        "GAP-OWN-03 resolved: empty-string promoted_from is normalized to None"
    );
    assert!(
        ownership.created_from.is_none(),
        "GAP-OWN-03 resolved: empty-string created_from is normalized to None"
    );
    // Mirror mode is still correctly deserialized
    assert_eq!(ownership.ownership_mode, Some(OwnershipMode::Mirror));
    assert_eq!(ownership.backend_kind, Some(BackendKind::Json));
    assert!(ownership.validate_structured().is_ok());
}

#[test]
fn test_mirror_fixture_empty_promoted_from_valid_in_python_raw() {
    // The Python-side raw JSON proves the record is valid:
    // ownership_mode=mirror, promoted_from="" (semantically empty)
    let v = read_wire_fixture_value("mirror-original.json");
    assert_eq!(v["ownership_mode"].as_str(), Some("mirror"));
    assert!(
        v["promoted_from"].as_str() == Some("") || v["promoted_from"].is_null(),
        "promoted_from must be empty string or null (unset ancestry field)"
    );
    // On the Python side, validate_ownership_lineage accepts this because
    // the promoted_from check uses truthiness (bool("") is False).
    // The gap is purely at the Rust serde layer.
}

