#![cfg(feature = "cross-repo-fixtures")]

//! Cross-repo ownership wire-format integration tests.
//!
//! These tests validate that the mirror and promotion ownership guardrails
//! hold across the repo boundary: LimeNet (Rust) verifies that Python-emitted
//! ownership records from `meta-agent` carry the correct mode-specific
//! semantics and that the Rust-side `Ownership::validate_structured()`
//! enforces the same invariants as the Python-side
//! `assert_not_mirror_mode()` / `assert_has_promotion_intent()` guardrails.
//!
//! ## Guardrail 1 — mirror does not advance canonical state
//!
//! Mirror backends replicate the graph for read-only access.  Python enforces
//! this via `MirrorModeViolation`; Rust enforces it by rejecting mirror-mode
//! records that carry `promoted_from` (promotion lineage), and by requiring
//! `backend_kind` so the upstream source is identifiable.
//!
//! ## Guardrail 2 — promotion does not degenerate into dual-write
//!
//! Promotion-mode backends must declare a non-empty `promoted_from` lineage
//! reference before mutating state.  Python enforces this via
//! `PromotionModeViolation`; Rust enforces it by rejecting promotion-mode
//! records that omit `promoted_from`.
//!
//! ## Structural gaps documented here
//!
//! - **GAP-OWN-01** — Resolved: BackendKind enum vocabulary is now shared
//!   across Python and Rust (`json`, `local_limenet`, `remote_limenet`,
//!   `sqlite`, `postgres`).
//! - **GAP-OWN-02** — Resolved: OwnershipMode enum vocabulary is now shared
//!   across Python and Rust (`local_canonical`, `remote_canonical`,
//!   `mirror`, `promotion`).
//! - **GAP-OWN-03** — Empty-string vs Option::None for `promoted_from`:
//!   Python emits `"promoted_from": ""` for "not set"; Rust serde maps
//!   this to `Some("")`, triggering the mirror `invalid_transition` check
//!   that guards against reads that would advance canonical state.
//!
//! The JSON fixtures live in `.state/artifacts/ownership_wire/` and are
//! generated by the meta-agent fixture exporter.

use limenet::contracts::{BackendKind, Ownership, OwnershipMode};
use std::fs;
use std::path::PathBuf;

/// Resolve the wire fixture directory, checking multiple candidate locations.
///
/// Primary: `<repo-parent>/.state/artifacts/ownership_wire/` (full workspace)
/// Fallback: `<repo>/tests/fixtures/ownership_wire/` (OpenSandbox bundle)
fn wire_dir() -> PathBuf {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let primary = manifest_dir
        .parent()
        .unwrap()
        .join(".state")
        .join("artifacts")
        .join("ownership_wire");
    if primary.exists() {
        return primary;
    }
    manifest_dir.join("tests").join("fixtures").join("ownership_wire")
}

fn read_wire_fixture(name: &str) -> String {
    let path = wire_dir().join(name);
    fs::read_to_string(&path).unwrap_or_else(|e| panic!("failed to read {path:?}: {e}"))
}

fn read_wire_fixture_value(name: &str) -> serde_json::Value {
    let text = read_wire_fixture(name);
    serde_json::from_str(&text).expect("fixture must be valid JSON")
}

